// Generates THIRD_PARTY_NOTICES with the license of every third-party package shipped in the
// desktop app (README §5, SECURITY.md). Chromium's own notices ship with Electron
// (LICENSES.chromium.html).
// Usage: node scripts/generate-notices.mjs [--check]   (--check fails when the file is outdated)
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUTPUT = 'THIRD_PARTY_NOTICES';

// Production dependencies of every workspace, plus packages the desktop app bundles from its
// devDependencies (Vite inlines them into out/). Electron's runtime ships, its tooling does not.
const SELECTOR = [
  '.prod',
  ...['react', 'react-dom', 'react-router', 'zod', '@fontsource-variable/inter'].flatMap((n) => [
    `#${n}`,
    `#${n} *`,
  ]),
  '#electron',
].join(', ');

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

const licenseOf = (p) =>
  typeof p.license === 'string' ? p.license : (p.license?.type ?? 'UNKNOWN');

const repositoryOf = (p) => {
  const url = typeof p.repository === 'string' ? p.repository : p.repository?.url;
  return url ? url.replace(/^git\+/, '').replace(/\.git$/, '') : null;
};

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8').replaceAll('\r\n', '\n').trim());
}

const packages = JSON.parse(
  execSync(`npm query "${SELECTOR}"`, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }),
);
const unique = new Map();
for (const p of packages) {
  if (!p.name || p.name === 'evully' || p.name.startsWith('@evully/')) continue;
  if (p.name.startsWith('@types/')) continue; // type declarations are not shipped
  unique.set(`${p.name}@${p.version}`, p);
}

const sections = [...unique.entries()]
  .sort(([a], [b]) => a.localeCompare(b, 'en'))
  .map(([id, p]) => {
    const texts = licenseTexts(p.path);
    const repo = repositoryOf(p);
    return [
      `${id}`,
      `License: ${licenseOf(p)}`,
      ...(repo ? [`Repository: ${repo}`] : []),
      '',
      texts.length
        ? texts.join('\n\n')
        : `(No license file included; declared license: ${licenseOf(p)})`,
    ].join('\n');
  });

const content = [
  'THIRD-PARTY SOFTWARE NOTICES',
  '',
  'Evully includes the third-party software listed below. Each package is',
  'distributed under its own license, reproduced here. Generated by',
  'scripts/generate-notices.mjs; do not edit by hand.',
  '',
  ...sections.flatMap((s) => ['='.repeat(72), s, '']),
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== content) {
    console.error(`${OUTPUT} is outdated. Run: npm run notices`);
    process.exit(1);
  }
  console.log(`ok: ${OUTPUT} up to date (${unique.size} packages)`);
} else {
  writeFileSync(OUTPUT, content);
  console.log(`wrote ${OUTPUT} (${unique.size} packages)`);
}
